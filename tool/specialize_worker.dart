import 'registry.dart';

/// The adapter for each structure: the library under lib/structures/ and the
/// constructor to call. Adding a structure means writing an adapter there and
/// adding one line here (see DEVELOPMENT.md).
const workerAdapters = <String, ({String library, String constructor})>{
  'unsorted_array_list': (library: 'lists', constructor: 'ArrayListAdapter.unsorted'),
  'unsorted_linked_list': (library: 'lists', constructor: 'LinkedListAdapter.unsorted'),
  'sorted_array_list': (library: 'lists', constructor: 'ArrayListAdapter.sorted'),
  'sorted_linked_list': (library: 'lists', constructor: 'LinkedListAdapter.sorted'),
  'tree': (library: 'trees', constructor: 'TreeAdapter.bst'),
  'avl': (library: 'trees', constructor: 'TreeAdapter.avl'),
  'stack': (library: 'stacks', constructor: 'ArrayStackAdapter'),
  'linked_stack': (library: 'stacks', constructor: 'LinkedStackAdapter'),
  'linked_queue': (library: 'queues', constructor: 'LinkedQueueAdapter'),
  'array_queue': (library: 'queues', constructor: 'ArrayQueueAdapter'),
  'array_heap': (library: 'heaps', constructor: 'ArrayHeapAdapter'),
  'node_heap': (library: 'heaps', constructor: 'NodeHeapAdapter'),
  'hash': (library: 'hash', constructor: 'HashAdapter'),
};

const _package = 'package:data_structure_sandbox_browser';

/// The entry point for one selected student file. The shared session
/// (lib/worker/session.dart) and the structure's adapter
/// (lib/structures/*.dart) do all the work; this file only connects them to
/// the instrumented copy of the student's class in `generated/<id>/`.
String generateWorker({
  required StructureSpec selected,
  required String id,
  required String sourcePath,
}) {
  final adapter = workerAdapters[selected.id];
  if (adapter == null) throw StateError('No worker adapter for ${selected.id}.');
  final type = 'student.${selected.className}';
  return '''
// Generated by tool/specialize_worker.dart for $sourcePath. Do not edit.
import '$_package/structures/${adapter.library}.dart';
import '$_package/worker/session.dart';
import 'generated/$id/${selected.filename}' as student;
import 'generated/$id/${selected.id}_methods.dart' as methods;

Future<void> main() => runWorker(
      ${adapter.constructor}(
        create: () => $type(),
        invoke: (instance, name, args) =>
            methods.invokeDiscovered(instance as $type, name, args),
        methodsJson: methods.discoveredMethodsJson,
      ),
      sourcePath: ${_dartString(sourcePath)},
      generatedFile: ${_dartString(selected.filename)},
    );
''';
}

/// A raw single-quoted Dart literal; student paths never contain quotes or
/// line breaks (see studentFolder and implementationFile).
String _dartString(String value) {
  if (value.contains("'") || value.contains('\n') || value.contains('\r')) {
    throw FormatException('Unsupported characters in path: $value');
  }
  return "r'$value'";
}
